export function getExamFaqs(exam: {
  slug: string
  name: string
  shortName: string
  papers?: number
  totalQuestions?: number
  subjects?: string[]
}): FaqItem[] {
  if (examFaqs[exam.slug] && examFaqs[exam.slug].length > 0) {
    return examFaqs[exam.slug]
  }
  const p = exam.papers ?? 0
  const q = exam.totalQuestions ?? 0
  const subs = (exam.subjects ?? []).filter(Boolean).join(', ')
  const items: FaqItem[] = []
  if (p > 0 && q > 0) {
    items.push({
      q: `How many ${exam.name} previous year question papers (PYQ) are solved on this page?`,
      a: `This page provides ${p} solved ${exam.name} (${exam.shortName}) previous year question paper${p > 1 ? 's' : ''} containing ${q.toLocaleString('en-IN')} solved MCQs with official answer keys and step-by-step explanations.`,
    })
  }
  if (subs) {
    items.push({
      q: `Which subjects are covered in ${exam.shortName} previous year question papers?`,
      a: `The solved ${exam.shortName} question papers on this page cover ${subs}. You can practice full year-wise papers or filter questions by subject and sub-topic.`,
    })
  }
  items.push({
    q: `Are the ${exam.shortName} answer keys and explanations free on Ministry of Papers?`,
    a: `Yes. All ${exam.name} previous year question papers, official answer keys, and detailed explanations are completely free to read and attempt online in timed mode.`,
  })
  return items
}
